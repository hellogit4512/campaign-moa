// "대전 문화동" → 대전 문화동, "관악구 봉천동" → 서울 관악구, "사당역" → 서울 사당역
export function guessArea(label) {
  const clean = (label || "").replace(/[\[\]]/g, " ").replace(/^(릴스|클립|인스타|유튜브|쇼츠)\s+/, "").trim();
  if (!clean) return { province: null, district: null, region: null };
  const words = clean.split(/[\s\/]+/).filter(Boolean);
  const p = PROVINCE[words[0]];
  if (p) return { province: p, district: words[1] || null, region: [p, words[1]].filter(Boolean).join(" ") };
  const hit = TABLE.find(([n]) => clean.includes(n));
  if (hit) return { province: hit[1], district: words[0], region: `${hit[1]} ${words[0]}` };
  return { province: null, district: null, region: clean };
}
